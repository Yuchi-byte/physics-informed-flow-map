"""Proof-of-concept: invert a held-out FlatVel-A velocity map by DPS-style tilting.

Takes the trained flow prior over OpenFWI velocity maps, simulates seismic data ``d`` from
a held-out (validation-split) map with the Deepwave forward operator, then guided-samples
the prior toward ``d`` to recover the velocity. Plain script (no Hydra). Example:

    uv run python experiments/0002_fwi_tilting/poc.py --ckpt <0001 EMA ckpt> --guidance 1e-9 --steps 100 --n-samples 2

Caveats: ``d_obs`` is generated by the *same* noiseless forward operator used inside the
guidance term (an "inverse crime" — no observation noise, no operator mismatch), so the
recovery is optimistic relative to real FWI. The target is now drawn from the seed-0
validation split (genuinely held out of training).

Reports per-sample MAE/RMSE (m/s) vs the true map (oracle, needs ground truth) plus the
ground-truth-free pick (lowest data misfit), and the data-misfit reduction vs an unguided
sample. Writes a ``true | v_hat | error`` figure next to this script.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch
import torch.nn.functional as F

from physics_informed_flow_map.flow_matching.datasets import OpenFWIDatasetConfig
from physics_informed_flow_map.flow_matching.models import DiTModelConfig, build_model
from physics_informed_flow_map.flow_matching.openfwi import VMAX, VMIN
from physics_informed_flow_map.physics.forward import simulate
from physics_informed_flow_map.physics.tilt import guided_sample


def to_mps70(v_norm: torch.Tensor) -> torch.Tensor:
    """(B,1,64,64) in [-1,1] -> (B,70,70) velocity in m/s (clamped to the trained range)."""
    v70 = F.interpolate(v_norm, size=70, mode="bilinear", align_corners=False).clamp(
        -1.0, 1.0
    )
    return ((v70 + 1.0) / 2.0 * (VMAX - VMIN) + VMIN)[:, 0]


def held_out_native(target_index: int) -> tuple[int, np.ndarray]:
    """Return ``(global_index, native 70x70 m/s map)`` for the ``target_index``-th
    validation-split FlatVel-A map. Asserts the chosen map is genuinely held out."""
    cfg = OpenFWIDatasetConfig(families=["FlatVel_A"], resolution=64)
    full, _, val_idx = cfg._split()
    gidx = val_idx[target_index]
    assert gidx in set(val_idx), "target leaked out of the validation split"
    path, row = full.index[gidx]
    native = np.ascontiguousarray(np.load(path, mmap_mode="r")[row, 0])  # (70,70) m/s
    return gidx, native


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--ckpt",
        required=True,
        help="Path to a 0001 flow-matching EMA checkpoint (e.g. a "
        "runs/0001_flow_matching/<ts>/checkpoints/step_<N>_ema.pt). Point this at the "
        "BEST-val EMA checkpoint (0001's report finds best val at epoch 39), not the "
        "final one.",
    )
    ap.add_argument("--guidance", type=float, default=1e-9)
    ap.add_argument("--steps", type=int, default=100)
    ap.add_argument("--n-samples", type=int, default=2)
    ap.add_argument(
        "--target-index",
        type=int,
        default=0,
        help="Index into the seed-0 validation split selecting the held-out target map.",
    )
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    if not Path(args.ckpt).is_file():
        raise SystemExit(
            f"--ckpt not found: {args.ckpt}\n"
            "Train a 0001 openfwi prior first (uv run python "
            "experiments/0001_flow_matching/run.py experiment=openfwi) and point --ckpt "
            "at its best-val EMA checkpoint."
        )
    dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    torch.manual_seed(args.seed)

    # Prior: DiT 256/6/8 @ 64x64 (matches conf/model/dit.yaml).
    model = build_model(
        (1, 64, 64),
        None,
        DiTModelConfig(hidden=256, depth=6, num_heads=8, patch_size=4),
    ).to(dev)
    ckpt = torch.load(args.ckpt, map_location=dev, weights_only=False)
    model.load_state_dict(ckpt["model"])
    model.eval()

    # Held-out (val-split) FlatVel-A map (native 70x70, m/s) -> observed seismic data.
    gidx, native = held_out_native(args.target_index)
    v_true = torch.from_numpy(native).float().to(dev)
    d_obs = simulate(v_true).detach()
    print(f"target: val map global index {gidx} (native {tuple(v_true.shape)})")

    # Bridge: prior sample (B,1,64,64) in [-1,1] -> physical seismic data.
    def forward_fn(v_norm: torch.Tensor) -> torch.Tensor:
        v_mps = to_mps70(v_norm)
        return torch.stack([simulate(v_mps[b]) for b in range(v_mps.shape[0])])

    b = args.n_samples
    x0 = torch.randn(b, 1, 64, 64, device=dev)
    t_cond = torch.zeros(b, device=dev)

    def velocity_fn(x: torch.Tensor, t: float) -> torch.Tensor:
        tb = torch.full((x.shape[0],), t, device=dev)
        return model.v(tb, tb, x, t_cond, x0)

    guided = guided_sample(
        velocity_fn,
        x0,
        forward_fn,
        d_obs,
        sampler_steps=args.steps,
        guidance_strength=args.guidance,
        normalize_grad=True,
    )
    unguided = guided_sample(
        velocity_fn,
        x0,
        forward_fn,
        d_obs,
        sampler_steps=args.steps,
        guidance_strength=0.0,
    )

    vg = to_mps70(guided)
    mae = (vg - v_true).abs().mean(dim=(1, 2))
    rmse = ((vg - v_true) ** 2).mean(dim=(1, 2)).sqrt()
    dm_g = ((forward_fn(guided) - d_obs) ** 2).sum(dim=(1, 2, 3))
    dm_u = ((forward_fn(unguided) - d_obs) ** 2).sum(dim=(1, 2, 3))
    oracle = int(mae.argmin())  # needs ground truth — not available in a real inversion
    reported = int(dm_g.argmin())  # ground-truth-free pick: lowest data misfit

    print(f"guidance={args.guidance:g}  steps={args.steps}  n={b}")
    print(f"  MAE (m/s):  {[round(x) for x in mae.tolist()]}")
    print(
        f"  MAE summary: mean={round(float(mae.mean()))}  median={round(float(mae.median()))}  worst={round(float(mae.max()))}"
    )
    print(f"  RMSE (m/s): {[round(x) for x in rmse.tolist()]}")
    print(
        f"  oracle (needs GT) best MAE = {round(float(mae[oracle]))}  [sample {oracle}]"
    )
    print(
        f"  reported (lowest data misfit) MAE = {round(float(mae[reported]))}  [sample {reported}]"
    )
    print(
        f"  data misfit  guided={float(dm_g.mean()):.3e}  unguided={float(dm_u.mean()):.3e}  ratio={float(dm_g.mean() / dm_u.mean()):.3f}"
    )

    out = Path(__file__).parent / "poc_result.png"
    vt = v_true.cpu().numpy()
    vh = vg[reported].detach().cpu().numpy()  # ground-truth-free reconstruction
    fig, ax = plt.subplots(1, 3, figsize=(9, 3.2))
    ax[0].imshow(vt, cmap="viridis")
    ax[0].set_title("true v")
    ax[0].axis("off")
    ax[1].imshow(vh, cmap="viridis", vmin=vt.min(), vmax=vt.max())
    ax[1].set_title(f"v_hat, min-misfit (MAE {round(float(mae[reported]))} m/s)")
    ax[1].axis("off")
    im = ax[2].imshow(vh - vt, cmap="RdBu", vmin=-500, vmax=500)
    ax[2].set_title("error")
    ax[2].axis("off")
    fig.colorbar(im, ax=ax[2], fraction=0.046)
    fig.tight_layout()
    fig.savefig(out, dpi=140, bbox_inches="tight")
    print(f"  wrote {out}")


if __name__ == "__main__":
    main()
